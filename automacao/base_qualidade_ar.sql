-- Estrutura inicial para um banco qualidade_ar vazio.
CREATE TABLE IF NOT EXISTS public.localidade (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidade text NOT NULL UNIQUE,
    estado text NOT NULL,
    pais text NOT NULL,
    latitude double precision,
    longitude double precision
);

CREATE TABLE IF NOT EXISTS public.historico_qualidade_ar (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    localidade_id integer REFERENCES public.localidade(id),
    data_hora timestamp NOT NULL,
    fonte text NOT NULL,
    aqi_usa integer,
    aqi_cn integer,
    poluente_principal_usa text,
    poluente_principal_cn text,
    temperatura double precision,
    pressao double precision,
    umidade double precision,
    velocidade_vento double precision,
    direcao_vento double precision,
    sensacao_termica double precision,
    icone_clima text,
    indice_uv double precision
);