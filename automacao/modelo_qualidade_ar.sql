-- Executar no banco qualidade_ar em uma unica transacao.
-- Registros municipais existentes permanecem sem estacao_id.
CREATE TABLE IF NOT EXISTS public.estacao_qualidade_ar (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    localidade_id integer NOT NULL REFERENCES public.localidade(id),
    nome text NOT NULL,
    fonte text NOT NULL,
    url_fonte text NOT NULL UNIQUE,
    identificador_fonte text,
    latitude double precision,
    longitude double precision,
    status_operacional text NOT NULL DEFAULT 'nao_confirmado',
    primeira_leitura timestamp,
    ultima_leitura timestamp,
    UNIQUE (id, localidade_id),
    CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CHECK (primeira_leitura IS NULL OR ultima_leitura IS NULL
           OR primeira_leitura <= ultima_leitura)
);

ALTER TABLE public.historico_qualidade_ar
    ADD COLUMN IF NOT EXISTS estacao_id integer;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid='public.historico_qualidade_ar'::regclass
                   AND conname='fk_historico_estacao_localidade') THEN
        ALTER TABLE public.historico_qualidade_ar
            ADD CONSTRAINT fk_historico_estacao_localidade
            FOREIGN KEY (estacao_id, localidade_id)
            REFERENCES public.estacao_qualidade_ar(id, localidade_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid='public.historico_qualidade_ar'::regclass
                   AND conname='ck_historico_estacao_com_localidade') THEN
        ALTER TABLE public.historico_qualidade_ar
            ADD CONSTRAINT ck_historico_estacao_com_localidade
            CHECK (estacao_id IS NULL OR localidade_id IS NOT NULL);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_historico_ponto_data
    ON public.historico_qualidade_ar(localidade_id, estacao_id, data_hora);

-- Cadastro de duas estacoes identificadas no site publico; sem medicoes
-- e sem presumir status ativo/inativo/sazonal ou coordenadas da cidade.
INSERT INTO public.estacao_qualidade_ar(localidade_id, nome, fonte, url_fonte)
SELECT l.id, s.nome, 'IQAir / AirVisual', s.url
FROM public.localidade l
CROSS JOIN (VALUES
    ('Porto Velho - Brux',
     'https://www.iqair.com/air-quality/brazil/rondonia/porto-velho/porto-velho-brux'),
    ('Av. Pres. Dutra - Olaria',
     'https://www.iqair.com/air-quality/brazil/rondonia/porto-velho/av-pres-dutra-olaria')
) AS s(nome,url)
WHERE l.cidade='Porto Velho' AND l.estado='Rondonia' AND l.pais='Brazil'
ON CONFLICT (url_fonte) DO NOTHING;

CREATE OR REPLACE VIEW public.bi_pontos_qualidade_ar AS
SELECT 'cidade:' || l.id::text AS ponto_id,
       l.id AS localidade_id, NULL::integer AS estacao_id,
       l.cidade, l.estado, l.pais,
       'cidade'::text AS tipo,
       'Agregado municipal'::text AS estacao,
       l.cidade || ' - Agregado municipal' AS ponto,
       l.latitude, l.longitude, NULL::text AS fonte_cadastro,
       'nao_se_aplica'::text AS status_operacional
FROM public.localidade l
WHERE l.estado='Rondonia' AND l.pais='Brazil'
UNION ALL
SELECT 'estacao:' || e.id::text, l.id, e.id,
       l.cidade, l.estado, l.pais, 'estacao', e.nome,
       l.cidade || ' - ' || e.nome,
       e.latitude, e.longitude, e.fonte, e.status_operacional
FROM public.estacao_qualidade_ar e
JOIN public.localidade l ON l.id=e.localidade_id
WHERE l.estado='Rondonia' AND l.pais='Brazil';

CREATE OR REPLACE VIEW public.bi_historico_qualidade_ar AS
SELECT h.*,
       CASE WHEN h.estacao_id IS NOT NULL THEN 'estacao:' || h.estacao_id::text
            WHEN h.localidade_id IS NOT NULL THEN 'cidade:' || h.localidade_id::text
            ELSE NULL END AS ponto_id,
       h.data_hora::date AS data,
       CASE WHEN h.estacao_id IS NOT NULL THEN 'estacao'
            WHEN h.localidade_id IS NOT NULL THEN 'cidade'
            ELSE 'nao_identificado' END AS tipo_medicao
FROM public.historico_qualidade_ar h;

COMMENT ON COLUMN public.historico_qualidade_ar.estacao_id IS
    'NULL: leitura municipal ou localidade desconhecida; nao inferir estacao.';
COMMENT ON VIEW public.bi_historico_qualidade_ar IS
    'Historico sem preenchimento de lacunas. data usa o timestamp legado sem conversao de fuso.';

CREATE OR REPLACE VIEW public.bi_calendario_qualidade_ar AS
SELECT d::date AS data, extract(year FROM d)::integer AS ano,
       extract(month FROM d)::integer AS mes_num,
       extract(day FROM d)::integer AS dia
FROM generate_series('2025-01-01'::timestamp,
    greatest((CURRENT_TIMESTAMP AT TIME ZONE 'America/Manaus')::date,
             coalesce((SELECT max(data_hora)::date FROM public.historico_qualidade_ar),
                      '2025-01-01'::date))::timestamp,
    interval '1 day') AS d;
